#!/usr/bin/env node
/**
 * Assemble `lib/client.js` from the catalog, the client core and every game file.
 *
 * The output is the exact shape the Harness Web client expects:
 *   window.__ModuleLoader__.load({ id: '<package name>', factory(require) { ... } })
 *
 * `--check` validates without writing (used by the test suite and before install).
 */
import { readFileSync, readdirSync, writeFileSync, existsSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)))
const PACKAGE_NAME = JSON.parse(readFileSync(join(ROOT, 'package.json'), 'utf8')).name
const CATALOG_FILE = join(ROOT, 'shared', 'catalog.js')
const CORE_FILE = join(ROOT, 'client-src', 'core.js')
const SHARED_GL_FILE = join(ROOT, 'shared', 'gl3d.js')
const GAMES_DIR = join(ROOT, 'client-src', 'games')
const OUT_FILE = join(ROOT, 'lib', 'client.js')

const checkOnly = process.argv.includes('--check')

function fail(message) {
  console.error(`build: ${message}`)
  process.exit(1)
}

function stripModuleSyntax(source, label) {
  if (/(^|\n)\s*import\s+[^(]/.test(source)) fail(`${label} must not use import statements`)
  return source.replace(/(^|\n)\s*export\s+default\s+/g, '$1').replace(/(^|\n)\s*export\s+(const|let|var|function|class)\s+/g, '$1$2 ')
}

/** Game ids, read from the GAMES block only (PACKS ids look the same). */
function catalogIds(source) {
  const block = /export const GAMES = \[([\s\S]*?)\n\]/.exec(source)
  const text = block ? block[1] : source
  const ids = new Set()
  const pattern = /id:\s*'([a-z0-9]+)'/g
  let match
  while ((match = pattern.exec(text)) !== null) ids.add(match[1])
  return ids
}

function collectGames() {
  if (!existsSync(GAMES_DIR)) return []
  const games = []
  for (const pack of readdirSync(GAMES_DIR, { withFileTypes: true })) {
    if (!pack.isDirectory()) continue
    const dir = join(GAMES_DIR, pack.name)
    for (const entry of readdirSync(dir).sort()) {
      if (!entry.endsWith('.js')) continue
      games.push({ pack: pack.name, id: entry.slice(0, -3), file: join(dir, entry) })
    }
  }
  return games
}

const catalogSource = readFileSync(CATALOG_FILE, 'utf8')
const knownIds = catalogIds(catalogSource)
const coreSource = readFileSync(CORE_FILE, 'utf8')
const games = collectGames()
const problems = []

for (const game of games) {
  const source = readFileSync(game.file, 'utf8')
  if (!knownIds.has(game.id)) problems.push(`${game.pack}/${game.id}.js is not in shared/catalog.js`)
  const idMatch = /defineGame\(\s*\{[\s\S]{0,200}?id:\s*'([^']+)'/.exec(source)
  if (!idMatch) problems.push(`${game.pack}/${game.id}.js has no defineGame({ id: '...' })`)
  else if (idMatch[1] !== game.id) problems.push(`${game.pack}/${game.id}.js declares id '${idMatch[1]}'`)
  if (/^\s*import\s/m.test(source)) problems.push(`${game.pack}/${game.id}.js uses import`)
  if (/^\s*export\s/m.test(source)) problems.push(`${game.pack}/${game.id}.js uses export`)
}

const found = new Set(games.map((game) => game.id))
const missing = [...knownIds].filter((id) => !found.has(id) && !/^(arcade|runner|puzzle|reflex|word|board|rhythm|physics|en|zh|ja|ko|es|fr|de|ru|pt)$/.test(id))

if (problems.length > 0) {
  for (const problem of problems) console.error(`build: ${problem}`)
  process.exit(1)
}

const catalogBlock = stripModuleSyntax(catalogSource, 'shared/catalog.js')
const gl3dBlock = stripModuleSyntax(readFileSync(SHARED_GL_FILE, 'utf8'), 'shared/gl3d.js')
const coreBlock = stripModuleSyntax(coreSource, 'client-src/core.js')

const bundle = `/* Generated by build.mjs — do not edit. ${games.length} games. */
window.__ModuleLoader__.load({
  id: ${JSON.stringify(PACKAGE_NAME)},
  factory: (require) => {
    const React = require('react')
    const h = React.createElement

    const DEFINITIONS = []
    let TG = null
    ;(() => {
${catalogBlock}
      TG = { PACKS, GAMES, GAME_BY_ID, PACK_BY_ID, GOAL_TYPES, CONTROL_CODES, HOW_TO, howTo }
    })()

    function defineGame(definition) {
      const meta = TG.GAME_BY_ID.get(definition.id)
      DEFINITIONS.push({ ...definition, meta })
    }

${gl3dBlock}

${coreBlock}

${games.map((game) => `    // ── ${game.pack}/${game.id}.js ──\n    ;(() => {\n${readFileSync(game.file, 'utf8')}\n    })()`).join('\n\n')}

    return { inject, apply }
  },
})
`

try {
  // Compiles the generated script without executing it: catches syntax errors here.
  // eslint-disable-next-line no-new-func
  new Function(bundle)
} catch (error) {
  fail(`generated bundle does not parse: ${error?.message ?? error}`)
}

const bytes = Buffer.byteLength(bundle, 'utf8')
if (missing.length > 0) {
  console.warn(`build: ${missing.length} catalog games have no file yet: ${missing.slice(0, 12).join(', ')}${missing.length > 12 ? '…' : ''}`)
}

if (checkOnly) {
  console.log(`build: ok — ${games.length} games, ${(bytes / 1024).toFixed(1)} KiB (not written)`)
} else {
  writeFileSync(OUT_FILE, bundle, 'utf8')
  console.log(`build: wrote lib/client.js — ${games.length} games, ${(bytes / 1024).toFixed(1)} KiB`)
}
